/**
 * Печатные протоколы УЗИ — приватный набор бланков.
 *
 * Доступ намеренно ограничен: бланки принадлежат конкретному врачу конкретной
 * клиники и не должны появляться ни у других клиник, ни у других врачей.
 * Гейт — `UZI_TEMPLATES_ACCESS` ниже, проверка в `uziTemplatesService`.
 *
 * `html` — тело документа без обёртки: стили и «шапка» клиники добавляются
 * на клиенте (общий бланк с логотипом), поэтому здесь только разметка протокола.
 * Плейсхолдеры `{{patientName}}`, `{{patientBirth}}`, `{{date}}` подставляются
 * на клиенте перед показом в редакторе.
 *
 * Классы разметки (стилизуются в `uziProtocolStyles.ts` на фронте):
 *   .meta   — таблица «Ф.И.О. / Г.р. / Дата»
 *   .grid   — таблица показателей
 *   .pair   — двухколоночная таблица «ПРАВАЯ / ЛЕВАЯ»
 *   .opts   — список вариантов заключения (лишнее врач удаляет)
 *   .fill   — пустое поле под значение
 *   .norm   — референсные значения
 */

